	void ASERWarpperPrivate::pollWindow() {
		if (ShuttingDown) {
			return;
		}
		if (Capturing) {
#ifdef Q_OS_WIN
			HWND hwnd = reinterpret_cast<HWND>(CapturedHwnd);
			if (hwnd == nullptr || IsWindow(hwnd) == FALSE) {
				detachWindow();
			}
			else {
				syncOverlay();
			}
#endif
			return;
		}
#ifdef Q_OS_WIN
		HWND hwnd = findASEWindow();
		if (hwnd != nullptr) {
			captureWindow(reinterpret_cast<WId>(hwnd));
			return;
		}
		AserProcessRunning = isASEProcessRunning();
#else
		AserProcessRunning = false;
#endif
		updateUi();
	}

