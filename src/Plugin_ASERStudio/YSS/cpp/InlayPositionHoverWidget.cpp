	void InlayPositionHoverWidget::changeEvent(QEvent* event) {
		if (event->type() == QEvent::PaletteChange
			or event->type() == QEvent::ApplicationPaletteChange
			or event->type() == QEvent::StyleChange
			or event->type() == QEvent::ThemeChange) {
			updateConfirmButtonStyle();
		}
		// 浮窗收起后没有必要继续空转定时器。
		if (event->type() == QEvent::Hide) {
			pausePlayback();
			updatePlaybackControls();
		}
		InlayHintHoverWidget::changeEvent(event);
	}

