	void ASERProjectResourceBrowserPrivate::setupConnections() {
		for (int i = 0; i < CategoryButtons.size(); i++) {
			const ResourceCategory category = CategoryTable[i].Category;
			QObject::connect(CategoryButtons[i], &QToolButton::clicked, q, [this, category]() {
				if (category == CurrentCategory and category == ResourceCategory::CharPicture
					and not CurrentCharacterPath.isEmpty()) {
					// 再次点击人物立绘时，从人物详情返回总览
					closeCharacter();
					return;
				}
				switchCategory(category);
				});
		}
		QObject::connect(BackButton, &QToolButton::clicked, q, [this]() {
			closeCharacter();
			});

		const ImageCacheHelper* cache = ImageCacheHelper::getInstance();
		QObject::connect(cache, &ImageCacheHelper::imageThumbnailPrepared, q,
			[this](const QImage& image, const QString& filePath, const QSize& size) {
				onImageThumbnailPrepared(image, filePath, size);
			});
		QObject::connect(cache, &ImageCacheHelper::waveThumbnailPrepared, q,
			[this](const QImage& image, const QString& filePath, const QSize& size) {
				onWaveThumbnailPrepared(image, filePath, size);
			});

		QObject::connect(VISTM, &Visindigo::Widgets::ThemeManager::programThemeChanged, q, [this]() {
			onThemeChanged();
			});
	}

	void ASERProjectResourceBrowserPrivate::onThemeChanged() {
		const QColor textColor = VISTM->getPaletteTextColor();
		if (IconColor == textColor) {
			return;
		}
		IconColor = textColor;
		WaveColor = VISTM->getPaletteAccentColor();
		BackButton->setIcon(VIApp->getNamedFontIcon("Back", CategoryButtonIconSize, { IconColor }));
		for (int i = 0; i < CategoryButtons.size(); i++) {
			CategoryButtons[i]->setIcon(VIApp->getNamedFontIcon(CategoryTable[i].IconName, CategoryButtonIconSize, { IconColor }));
		}
		// 图标变化会影响按钮的宽度需求，因此重新分行
		CategoryButtonsPerRow = 0;
		const QPalette palette = q->palette();
		for (ASERResourceItemWidget* item : Items) {
			item->setWaveColor(WaveColor);
			item->setOverlayButtonColors(palette.color(QPalette::Window), palette.color(QPalette::Text),
				palette.color(QPalette::Mid), palette.color(QPalette::Highlight),
				palette.color(QPalette::HighlightedText));
		}
		// 占位图标与当前条目类型绑定，重建一次内容以刷新它们
		rebuildContent();
		relayoutCategoryBar();
	}

