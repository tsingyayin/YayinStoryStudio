	/*!
		\class ASERStudio::YSS::ASERProjectResourceBrowser
		\since ASERStudio 2.4.0
		\brief ASERProjectResourceBrowser以缩略图的方式浏览当前ASER项目中的资源.
		\inmodule ASERStudio

		ASERProjectResourceBrowser按照ASE-Remake约定解析当前项目的Resources目录，
		把资源分为背景、人物立绘、动态立绘、音效、音频与特效六类，顶部的按钮用于在这些类别之间切换。

		背景与人物立绘以缩略图网格展示，图片等比缩放、不会拉伸；人物立绘先以“总览”列出全部人物，
		单击一个人物即可进入该人物文件夹查看其中的全部内容。动态立绘以Spine贴图作为缩略图，
		鼠标悬浮时会在条目之上显示此动态立绘包含的各种文件，单击即可打开对应文件。
		音效与音频统一以长条展示，其中显示文件名与整曲响度的波形预览图。
		特效目前没有可用的预览图，因此以图标占位。

		各类缩略图均由ASERStudio::YSS::ImageCacheHelper异步生成并缓存，因此反复浏览相同内容时几乎不产生额外开销。

		\note ase-remake只支持WAV格式的音频，因此音频类别的浏览也只处理WAV文件。
	*/

	ASERProjectResourceBrowser::ASERProjectResourceBrowser(QWidget* parent) :
		YSSCore::Editor::FileEditWidget(parent) {
		d = new ASERProjectResourceBrowserPrivate();
		d->q = this;
		d->buildUi();
		d->setupConnections();
		d->onThemeChanged();
	}

	ASERProjectResourceBrowser::~ASERProjectResourceBrowser() {
		delete d;
	}

	/*!
		\since ASERStudio 2.4.0

		重新读取当前项目的Resources目录，并重建当前类别的全部内容。
	*/
	void ASERProjectResourceBrowser::refresh() {
		d->rebuildContent();
	}

	/*!
		\since ASERStudio 2.4.0
		\a ext 虚拟文件扩展名。
		\a fileName 虚拟文件名。
		\a param 虚拟文件参数。

		return 如果虚拟文件扩展名与本文件服务器匹配，则返回true，否则返回false。
	*/
	bool ASERProjectResourceBrowser::onVirtualOpen(const QString& ext, const QString& fileName, const QString& param) {
		if (ext == VirtualFileExt) {
			d->rebuildContent();
			return true;
		}
		return false;
	}

	/*!
		\since ASERStudio 2.4.0
		\a event 显示事件对象。

		当本控件重新显示时，如果当前项目的Resources目录与内容区反映的不一致，
		则回到初始状态并重新读取。
	*/
	void ASERProjectResourceBrowser::showEvent(QShowEvent* event) {
		YSSCore::Editor::FileEditWidget::showEvent(event);
		if (d->resourcesRoot() != d->ResourcesRootPath) {
			d->CurrentCharacterPath.clear();
			d->switchCategory(ResourceCategory::Background);
		}
	}

	/*!
		\since ASERStudio 2.4.0
		\a event 尺寸变化事件对象。

		重新按可用宽度排布内容区中的条目。条目尺寸固定不变，宽度变化只改变每行放置的数量。
	*/
	void ASERProjectResourceBrowser::resizeEvent(QResizeEvent* event) {
		YSSCore::Editor::FileEditWidget::resizeEvent(event);
		// 尺寸变化时子控件的布局还没更新完，此时立即重排会用到旧的宽度，
		// 因此推迟到下一次事件循环再排布。
		if (d->RelayoutPending) {
			return;
		}
		d->RelayoutPending = true;
		QTimer::singleShot(0, this, [this]() {
			d->RelayoutPending = false;
			d->relayoutAll();
			});
	}
