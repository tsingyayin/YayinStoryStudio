	/*
		取得人物文件夹中的配置文件路径。ASER约定配置名为 \c{<文件夹名>_config.json}，
		少数项目直接使用 \c{<文件夹名>.json}，因此两者都尝试。
	*/
	QString ASERProjectResourceBrowserPrivate::characterConfigPath(
		const QString& folderPath, const QString& folderName) const {
		static const QStringList nameSuffixes = { "_config.json", ".json" };
		for (const QString& suffix : nameSuffixes) {
			const QFileInfo candidate(folderPath + "/" + folderName + suffix);
			if (candidate.isFile()) {
				return candidate.absoluteFilePath();
			}
		}
		// 退而求其次：文件夹中任何以 _config.json 结尾的文件
		const QFileInfoList entries = QDir(folderPath).entryInfoList(
			{ "*_config.json" }, QDir::Files, QDir::Name | QDir::IgnoreCase);
		if (not entries.isEmpty()) {
			return entries.first().absoluteFilePath();
		}
		return QString();
	}

	/*
		取得人物文件夹中用于预览的贴图。它来自人物配置中第一个差分记录的主体贴图，
		取不到时返回空字符串，由调用方决定降级方案。
	*/
	QString ASERProjectResourceBrowserPrivate::characterBodyTexturePath(
		const QString& folderPath, const QString& folderName) const {
		const QString configPath = characterConfigPath(folderPath, folderName);
		if (configPath.isEmpty()) {
			return QString();
		}
		Visindigo::Utility::FileOperation::Errorable<QString> content =
			Visindigo::Utility::FileOperation::readAll(configPath);
		if (not content) {
			vgWarningF << "Failed to read the character config:" << configPath
				<< ", error:" << Visindigo::Utility::FileOperation::errorCodeName(content.error());
			return QString();
		}
		Visindigo::Utility::JsonConfig config;
		if (config.parse(content.value()).error != QJsonParseError::NoError) {
			return QString();
		}
		const QStringList variations = config.keys("variations");
		if (variations.isEmpty()) {
			return QString();
		}
		const QString variationKey = variations.first();
		QString bodyTexture = config.getString("variations." + variationKey + ".bodyTexturePath");
		if (bodyTexture.isEmpty()) {
			// 极少数配置使用C#侧的大写属性名
			bodyTexture = config.getString("variations." + variationKey + ".BodyTexturePath");
		}
		return resolveProjectPath(bodyTexture);
	}

	void ASERProjectResourceBrowserPrivate::switchCategory(ResourceCategory category) {
		CurrentCategory = category;
		CurrentCharacterPath.clear();
		const int index = static_cast<int>(category);
		if (index >= 0 and index < CategoryButtons.size() and not CategoryButtons[index]->isChecked()) {
			CategoryButtons[index]->setChecked(true);
		}
		rebuildContent();
	}

	void ASERProjectResourceBrowserPrivate::openCharacter(const QString& folderPath) {
		CurrentCharacterPath = folderPath;
		rebuildContent();
	}

	void ASERProjectResourceBrowserPrivate::closeCharacter() {
		if (CurrentCharacterPath.isEmpty()) {
			return;
		}
		CurrentCharacterPath.clear();
		rebuildContent();
	}

	void ASERProjectResourceBrowserPrivate::updateHeader() {
		const bool characterView = (CurrentCategory == ResourceCategory::CharPicture);
		HeaderRow->setVisible(characterView);
		if (not characterView) {
			return;
		}
		if (CurrentCharacterPath.isEmpty()) {
			BackButton->setVisible(false);
			BackIndent->setVisible(true);
			HeaderLabel->setText(VITRL("ASERStudio::projectResourceBrowser.overview"));
		}
		else {
			BackButton->setVisible(true);
			BackIndent->setVisible(false);
			HeaderLabel->setText(QFileInfo(CurrentCharacterPath).fileName());
		}
	}

	void ASERProjectResourceBrowserPrivate::clearItems() {
		for (ASERResourceItemWidget* item : Items) {
			delete item;
		}
		Items.clear();
	}

	ASERResourceItemWidget* ASERProjectResourceBrowserPrivate::createItem(ResourceItemKind kind) {
		ASERResourceItemWidget* item = new ASERResourceItemWidget(kind, ItemsHost);
		item->setWaveColor(WaveColor);
		item->setOnDoubleClick([this](ASERResourceItemWidget* source) {
			// 激活会重建列表并销毁发出信号的条目，因此延后到本次事件处理结束之后再执行
			const QString filePath = source->getFilePath();
			const ResourceItemKind kind = source->getKind();
			QTimer::singleShot(0, q, [this, filePath, kind]() {
				// 文件夹是进入其中浏览，其余内容都是打开文件
				if (kind == ResourceItemKind::Folder) {
					openCharacter(filePath);
				}
				else {
					openResourceFile(filePath);
				}
				});
			});
		item->setOnFileAction([this](const QString& filePath) {
			QTimer::singleShot(0, q, [this, filePath]() {
				openResourceFile(filePath);
				});
			});
		const QPalette palette = q->palette();
		item->setOverlayButtonColors(palette.color(QPalette::Window), palette.color(QPalette::Text),
			palette.color(QPalette::Mid), palette.color(QPalette::Highlight),
			palette.color(QPalette::HighlightedText));
		Items.append(item);
		return item;
	}

	void ASERProjectResourceBrowserPrivate::requestImageThumbnail(
		ASERResourceItemWidget* item, const QString& imagePath, const QSize& size) {
		item->setThumbnailRequest(imagePath, size);
		item->setPlaceholderIcon(namedIcon("Photo"));
		ImageCacheHelper::getInstance()->requestThumbnailForImage(imagePath, size);
	}

	void ASERProjectResourceBrowserPrivate::requestWaveThumbnail(
		ASERResourceItemWidget* item, const QString& wavePath, const QSize& size) {
		item->setThumbnailRequest(wavePath, size);
		ImageCacheHelper::getInstance()->requestThumbnailForWAVE(wavePath, size);
	}

	void ASERProjectResourceBrowserPrivate::onImageThumbnailPrepared(
		const QImage& image, const QString& filePath, const QSize& size) {
		if (image.isNull()) {
			return;
		}
		for (ASERResourceItemWidget* item : Items) {
			if (item->getThumbnailPath() == filePath and item->getThumbnailSize() == size) {
				item->setThumbnail(image);
			}
		}
	}

	void ASERProjectResourceBrowserPrivate::onWaveThumbnailPrepared(
		const QImage& image, const QString& filePath, const QSize& size) {
		if (image.isNull()) {
			return;
		}
		for (ASERResourceItemWidget* item : Items) {
			if (item->getKind() != ResourceItemKind::Audio) {
				continue;
			}
			if (item->getThumbnailPath() == filePath and item->getThumbnailSize() == size) {
				item->setThumbnail(image);
			}
		}
	}

	void ASERProjectResourceBrowserPrivate::openResourceFile(const QString& filePath) {
		if (filePath.isEmpty()) {
			return;
		}
		YSSFSM->openFile(filePath);
	}

	void ASERProjectResourceBrowserPrivate::buildFileGridView(
		const QString& dirPath, qreal aspect, const QSize& thumbnailSize, bool imagesFirst) {
		QFileInfoList entries = QDir(dirPath).entryInfoList(
			QDir::Files | QDir::NoDotAndDotDot, QDir::Name | QDir::IgnoreCase);
		if (imagesFirst) {
			std::stable_partition(entries.begin(), entries.end(), [](const QFileInfo& info) {
				return isImageFile(info.suffix());
				});
		}
		for (const QFileInfo& entry : entries) {
			ASERResourceItemWidget* item = createItem(ResourceItemKind::Image);
			item->setTitle(entry.fileName());
			item->setFilePath(entry.absoluteFilePath());
			item->setCellAspect(aspect);
			if (isImageFile(entry.suffix())) {
				requestImageThumbnail(item, entry.absoluteFilePath(), thumbnailSize);
			}
			else {
				item->setPlaceholderIcon(namedIcon(entry.suffix().compare("json", Qt::CaseInsensitive) == 0
					? "Code" : "Document"));
			}
		}
	}

	void ASERProjectResourceBrowserPrivate::buildCharacterOverview() {
		const QString dirPath = categoryPath(ResourceCategory::CharPicture);
		const QFileInfoList folders = QDir(dirPath).entryInfoList(
			QDir::Dirs | QDir::NoDotAndDotDot, QDir::Name | QDir::IgnoreCase);
		for (const QFileInfo& folder : folders) {
			const QString folderName = folder.fileName();
			// 优先使用人物配置中记录的主体贴图，取不到时退回文件夹中的第一张图片
			QString preview = characterBodyTexturePath(folder.absoluteFilePath(), folderName);
			if (preview.isEmpty()) {
				preview = firstImageInDirectory(folder.absoluteFilePath(), false);
			}
			ASERResourceItemWidget* item = createItem(ResourceItemKind::Folder);
			item->setTitle(folderName);
			item->setFilePath(folder.absoluteFilePath());
			item->setCellAspect(SquareAspect);
			if (preview.isEmpty()) {
				item->setPlaceholderIcon(namedIcon("Contact2"));
			}
			else {
				requestImageThumbnail(item, preview, CharacterThumbnailSize);
			}
		}
	}

	void ASERProjectResourceBrowserPrivate::buildCharacterDetail(const QString& folderPath) {
		buildFileGridView(folderPath, SquareAspect, CharacterThumbnailSize, true);
	}

	void ASERProjectResourceBrowserPrivate::buildSpineView() {
		const QString dirPath = categoryPath(ResourceCategory::CharSpine);
		const QFileInfoList folders = QDir(dirPath).entryInfoList(
			QDir::Dirs | QDir::NoDotAndDotDot, QDir::Name | QDir::IgnoreCase);
		for (const QFileInfo& folder : folders) {
			const QString folderName = folder.fileName();
			const QString folderPath = folder.absoluteFilePath();
			const QString texturePath = folderPath + "/" + folderName + ".png";
			QString preview = QFileInfo::exists(texturePath)
				? texturePath : firstImageInDirectory(folderPath, false);
			if (preview.isEmpty()) {
				continue; // 没有贴图就无法提供缩略图，此时不显示这个动态立绘
			}
			ASERResourceItemWidget* item = createItem(ResourceItemKind::Spine);
			item->setTitle(folderName);
			item->setFilePath(folderPath);
			item->setCellAspect(SquareAspect);
			requestImageThumbnail(item, preview, CharacterThumbnailSize);

			QList<QPair<QString, QString>> buttons;
			const QString atlasPath = folderPath + "/" + folderName + ".atlas";
			const QString skelPath = folderPath + "/" + folderName + ".skel";
			const QString spineProjectPath = folderPath + "/" + folderName + ".json";
			const QString aserConfigPath = folderPath + "/" + folderName + "_config.json";
			if (QFileInfo::exists(atlasPath)) {
				buttons.append({ VITRL("ASERStudio::projectResourceBrowser.spine.atlas"), atlasPath });
			}
			if (QFileInfo::exists(texturePath)) {
				buttons.append({ VITRL("ASERStudio::projectResourceBrowser.spine.texture"), texturePath });
			}
			if (QFileInfo::exists(skelPath)) {
				buttons.append({ VITRL("ASERStudio::projectResourceBrowser.spine.skeleton"), skelPath });
			}
			if (QFileInfo::exists(aserConfigPath)) {
				buttons.append({ VITRL("ASERStudio::projectResourceBrowser.spine.aserConfig"), aserConfigPath });
			}
			if (QFileInfo::exists(spineProjectPath)) {
				buttons.append({ VITRL("ASERStudio::projectResourceBrowser.spine.spineProject"), spineProjectPath });
			}
			item->setOverlayButtons(buttons);
		}
	}

	void ASERProjectResourceBrowserPrivate::buildAudioView(const QString& dirPath) {
		const QFileInfoList entries = QDir(dirPath).entryInfoList(
			QDir::Files | QDir::NoDotAndDotDot, QDir::Name | QDir::IgnoreCase);
		for (const QFileInfo& entry : entries) {
			if (not isWaveFile(entry.suffix())) {
				continue; // ASE-Remake只支持WAV格式的音频
			}
			ASERResourceItemWidget* item = createItem(ResourceItemKind::Audio);
			item->setTitle(entry.fileName());
			item->setFilePath(entry.absoluteFilePath());
			requestWaveThumbnail(item, entry.absoluteFilePath(), AudioThumbnailSize);
		}
	}

	void ASERProjectResourceBrowserPrivate::buildEffectView() {
		const QString dirPath = categoryPath(ResourceCategory::VisualEffect);
		// 特效目录中内容都放在子目录里，因此这里连同子目录一起列出
		QStringList files = Visindigo::Utility::FileUtility::fileFilter(dirPath, { "*.*" }, true);
		std::sort(files.begin(), files.end(), [](const QString& left, const QString& right) {
			return QString::compare(left, right, Qt::CaseInsensitive) < 0;
			});
		for (const QString& file : files) {
			ASERResourceItemWidget* item = createItem(ResourceItemKind::Placeholder);
			item->setTitle(QFileInfo(file).fileName());
			item->setFilePath(file);
			item->setCellAspect(WideAspect);
			item->setPlaceholderIcon(namedIcon("SpecialEffectSize"));
		}
	}

	void ASERProjectResourceBrowserPrivate::rebuildContent() {
		clearItems();
		updateHeader();
		if (ensureResourcesRoot()) {
			switch (CurrentCategory) {
			case ResourceCategory::Background:
				buildFileGridView(categoryPath(ResourceCategory::Background), WideAspect, BackgroundThumbnailSize, false);
				break;
			case ResourceCategory::CharPicture:
				if (CurrentCharacterPath.isEmpty()) {
					buildCharacterOverview();
				}
				else {
					buildCharacterDetail(CurrentCharacterPath);
				}
				break;
			case ResourceCategory::CharSpine:
				buildSpineView();
				break;
			case ResourceCategory::SoundEffect:
				buildAudioView(categoryPath(ResourceCategory::SoundEffect));
				break;
			case ResourceCategory::Music:
				buildAudioView(categoryPath(ResourceCategory::Music));
				break;
			case ResourceCategory::VisualEffect:
				buildEffectView();
				break;
			}
		}
		relayoutItems();
	}

	void ASERProjectResourceBrowserPrivate::relayoutAll() {
		relayoutCategoryBar();
		relayoutItems();
	}

	/*
		按可用宽度决定分类按钮每行放几个。面板很窄时将它们折成多行，
		而不是让文字被省略号截断。
	*/
	void ASERProjectResourceBrowserPrivate::relayoutCategoryBar() {
		if (CategoryButtons.isEmpty()) {
			return;
		}
		const int available = qMax(80, q->width() - 16);
		const int spacing = 4;
		// 先算出一个按钮都不省略时需要的总宽度
		int totalWidth = -spacing;
		for (QToolButton* button : CategoryButtons) {
			totalWidth += button->sizeHint().width() + spacing;
		}
		if (totalWidth <= 0) {
			return;
		}
		// 一行放不下就折行，并把按钮尽量平均地分配到各行
		int rows = 1;
		if (totalWidth > available) {
			rows = (totalWidth + available - 1) / available;
		}
		int perRow = (CategoryButtons.size() + rows - 1) / rows;
		perRow = qBound(1, perRow, CategoryButtons.size());
		if (perRow == CategoryButtonsPerRow) {
			return;
		}
		rebuildCategoryRows(perRow);
	}

	void ASERProjectResourceBrowserPrivate::rebuildCategoryRows(int perRow) {
		CategoryButtonsPerRow = perRow;
		// 先把按钮从旧的行里摘出来，再销毁旧的行
		for (QWidget* row : CategoryRowWidgets) {
			row->setParent(nullptr);
		}
		for (QWidget* row : CategoryRowWidgets) {
			row->deleteLater();
		}
		CategoryRowWidgets.clear();
		QList<QToolButton*> pending = CategoryButtons;
		const int spacing = 4;
		while (not pending.isEmpty()) {
			QWidget* row = new QWidget(CategoryBar);
			QHBoxLayout* rowLayout = new QHBoxLayout(row);
			rowLayout->setContentsMargins(0, 0, 0, 0);
			rowLayout->setSpacing(spacing);
			rowLayout->addStretch(1);
			for (int i = 0; i < perRow and not pending.isEmpty(); i++) {
				rowLayout->addWidget(pending.takeFirst());
			}
			rowLayout->addStretch(1);
			CategoryRowsLayout->addWidget(row);
			CategoryRowWidgets.append(row);
		}
	}

	void ASERProjectResourceBrowserPrivate::relayoutItems() {
		while (ItemsLayout->count() > 0) {
			QLayoutItem* layoutItem = ItemsLayout->takeAt(0);
			delete layoutItem; // 只删除布局项，条目本身仍然由父控件持有
		}
		EmptyLabel->hide();
		EmptyLabel->setParent(ItemsHost);
		// 上一次设置的行拉伸必须先复位，理由见setStretchRow的说明
		clearStretchRow();

		// 视口宽度已经扣除了可见的竖直滚动条；滚动条还没出现时先把它的宽度预留出来，
		// 这样滚动条出现或消失都不会让条目的宽度来回跳。再扣掉内容区自己的左右边距。
		QScrollBar* scrollBar = ContentScroll->verticalScrollBar();
		const int reservedScrollBar = scrollBar->isVisible() ? 0 : scrollBar->sizeHint().width();
		int available = ContentScroll->viewport()->width() - 2 * ContentMargin - reservedScrollBar;
		available = qMax(120, available);

		if (Items.isEmpty()) {
			ItemsHost->setFixedWidth(available);
			EmptyLabel->show();
			EmptyLabel->setFixedWidth(qMax(80, available - 2 * ItemPadding));
			ItemsLayout->addWidget(EmptyLabel, 0, 0, 1, 1, Qt::AlignCenter);
			setStretchRow(0);
			return;
		}

		const bool barMode = (CurrentCategory == ResourceCategory::SoundEffect
			or CurrentCategory == ResourceCategory::Music);
		int blockWidth = available;
		if (barMode) {
			// 音频每行一个，整条从左到右占满一行
			for (int i = 0; i < Items.size(); i++) {
				Items[i]->setCellWidth(available);
				ItemsLayout->addWidget(Items[i], i, 0, Qt::AlignHCenter | Qt::AlignTop);
			}
			setStretchRow(Items.size());
		}
		else {
			// 图片按默认尺寸铺排，每行能放几个就放几个，宽度变化只影响一行的数量。
			const int cellWidth = qMin(cellWidthOf(CurrentCategory), available);
			const int columns = qMax(1, (available + GridSpacing) / (cellWidth + GridSpacing));
			for (int i = 0; i < Items.size(); i++) {
				Items[i]->setCellWidth(cellWidth);
				ItemsLayout->addWidget(Items[i], i / columns, i % columns, Qt::AlignHCenter | Qt::AlignTop);
			}
			blockWidth = columns * cellWidth + (columns - 1) * GridSpacing;
			setStretchRow((Items.size() + columns - 1) / columns);
		}
		// 内容块宽度固定后由外层布局居中，这样左右留白始终相等
		ItemsHost->setFixedWidth(blockWidth);
	}

