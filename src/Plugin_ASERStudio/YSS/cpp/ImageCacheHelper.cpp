	void ImageCacheHelper::requestThumbnailForImage(const QString& filePath, QSize targetSize) {
		if (d->Stopped or filePath.isEmpty()) {
			return;
		}
		if (targetSize.width() <= 0 or targetSize.height() <= 0) {
			return;
		}
		const QString absPath = QFileInfo(filePath).absoluteFilePath();
		const QString key = requestKeyOf(false, absPath, targetSize);
		if (d->PendingRequests.contains(key)) {
			return;
		}
		d->PendingRequests.insert(key);
		ImageCacheWorker* worker = d->Worker;
		QMetaObject::invokeMethod(worker, [worker, absPath, targetSize]() {
			worker->generateImageThumbnail(absPath, targetSize);
			}, Qt::QueuedConnection);
	}

