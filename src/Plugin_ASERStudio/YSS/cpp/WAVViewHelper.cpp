	/*!
		\since ASERStudio 2.4.0
		\a filePath WAV文件的路径。
		\a bucketCount 期望的响度采样点数量，对应预览图的水平像素数。
		\a loudness 用于接收响度曲线的列表。

		return 是否成功读出响度曲线。

		按 \a bucketCount 把整曲平分为若干个区间，计算每个区间内所有采样的均方根响度，
		并最终按整曲的最大值归一化到0.0~1.0。因此这个曲线的形状反映的是整曲的相对响度分布。

		\a bucketCount 小于1时会被视为1。返回的列表长度可能少于 \a bucketCount
		（当音频的采样帧数量不足时）。
	*/
	bool WAVViewHelper::readLoudnessCurve(const QString& filePath, qint32 bucketCount, QList<qreal>& loudness) {
		loudness.clear();
		if (bucketCount < 1) {
			bucketCount = 1;
		}
		QFile file(filePath);
		WAVFormat format;
		qint64 dataOffset = 0;
		qint64 dataSize = 0;
		if (not parseHeader(file, format, dataOffset, dataSize) or not isFormatSupported(format)) {
			return false;
		}
		const qint64 frameCount = dataSize / format.BlockAlign;
		if (frameCount <= 0) {
			return false;
		}
		const qint64 framesPerBucket = qMax<qint64>(1, frameCount / bucketCount);
		file.seek(dataOffset);

		QList<double> sumOfSquares;
		QList<qint64> frameCounts;
		const int readBufferSize = qMax<int>(format.BlockAlign * 4096, format.BlockAlign);
		QByteArray buffer;
		qint64 remainingFrames = frameCount;
		qint64 framesInBucket = 0;
		double squareSum = 0.0;
		// 逐块读取音频数据，边读边累加每个桶的能量
		while (remainingFrames > 0) {
			const qint64 framesToRead = qMin<qint64>(readBufferSize / format.BlockAlign, remainingFrames);
			const qint64 bytesToRead = framesToRead * format.BlockAlign;
			buffer = file.read(bytesToRead);
			const qint64 availableFrames = buffer.size() / format.BlockAlign;
			if (availableFrames <= 0) {
				break;
			}
			for (qint64 frame = 0; frame < availableFrames; frame++) {
				const double amplitude = frameAmplitude(buffer.constData() + frame * format.BlockAlign, format);
				squareSum += amplitude * amplitude;
				framesInBucket++;
				if (framesInBucket >= framesPerBucket) {
					sumOfSquares.append(squareSum);
					frameCounts.append(framesInBucket);
					squareSum = 0.0;
					framesInBucket = 0;
				}
			}
			remainingFrames -= availableFrames;
		}
		if (framesInBucket > 0) {
			sumOfSquares.append(squareSum);
			frameCounts.append(framesInBucket);
		}
		if (sumOfSquares.isEmpty()) {
			return false;
		}
		double maxLoudness = 0.0;
		loudness.reserve(sumOfSquares.size());
		for (int i = 0; i < sumOfSquares.size(); i++) {
			const double rms = std::sqrt(sumOfSquares[i] / static_cast<double>(frameCounts[i]));
			loudness.append(rms);
			maxLoudness = qMax(maxLoudness, rms);
		}
		if (maxLoudness <= 0.0) {
			// 整曲都是静音，此时给出一条平直的零响度曲线
			for (int i = 0; i < loudness.size(); i++) {
				loudness[i] = 0.0;
			}
			return true;
		}
		for (int i = 0; i < loudness.size(); i++) {
			loudness[i] = qBound(0.0, loudness[i] / maxLoudness, 1.0);
		}
		return true;
	}

	/*!
		\since ASERStudio 2.4.0
		\a image 目标图片，其内容会被直接绘制。
		\a loudness 已经归一化到0.0~1.0的响度曲线。
		\a waveColor 波形颜色。

		在 \a image 上以垂直居中的对称柱状图绘制响度曲线。列表中的每个元素对应一列像素，
		因此调用方应保证响度曲线的长度与图片宽度的关系符合自己的需要。
	*/
	void WAVViewHelper::renderLoudnessCurve(QImage& image, const QList<qreal>& loudness, const QColor& waveColor) {
		if (image.isNull() or loudness.isEmpty() or image.width() <= 0 or image.height() <= 0) {
			return;
		}
		QPainter painter(&image);
		painter.setRenderHint(QPainter::Antialiasing, false);
		painter.setPen(Qt::NoPen);
		painter.setBrush(waveColor);
		const int centerY = image.height() / 2;
		const int maxHalfHeight = qMax(1, (image.height() / 2) - 2);
		for (int x = 0; x < image.width(); x++) {
			// 响度曲线的长度与图片宽度不一定相等，这里按比例取样
			const int index = qBound(0, static_cast<int>(static_cast<qreal>(x) * loudness.size() / image.width()),
				loudness.size() - 1);
			int halfHeight = static_cast<int>(loudness[index] * maxHalfHeight + 0.5);
			halfHeight = qMax(1, halfHeight);
			painter.drawRect(x, centerY - halfHeight, 1, halfHeight * 2);
		}
	}

