	// 带超时的 TCP 连接。先设非阻塞再 select 等可写，这样 ConnectTimeoutMs 才真的生效；
	// 连接成功后再切回阻塞模式，交给 libssh2 阻塞式调用接管。
	quintptr openSocket(const Visindigo::Network::SshConnectConfig& config,
		Visindigo::Network::SshError* error) {
		struct addrinfo hints;
		memset(&hints, 0, sizeof(hints));
		hints.ai_family = AF_UNSPEC;
		hints.ai_socktype = SOCK_STREAM;
		hints.ai_protocol = IPPROTO_TCP;

		const QByteArray host = config.Host.toUtf8();
		const QByteArray port = QByteArray::number(config.Port);
		struct addrinfo* result = nullptr;
		if (getaddrinfo(host.constData(), port.constData(), &hints, &result) != 0) {
			*error = makeError(Visindigo::Network::SshError::ErrorType::HostNotFound,
				QStringLiteral("Cannot resolve host %1").arg(config.Host));
			return 0;
		}

		int lastError = 0;
		quintptr connected = 0;
		for (struct addrinfo* entry = result; entry != nullptr && connected == 0; entry = entry->ai_next) {
			SOCKET candidate = ::socket(entry->ai_family, entry->ai_socktype, entry->ai_protocol);
			if (candidate == INVALID_SOCKET) {
				lastError = WSAGetLastError();
				continue;
			}
			u_long nonBlocking = 1;
			ioctlsocket(candidate, FIONBIO, &nonBlocking);

			bool ready = false;
			if (::connect(candidate, entry->ai_addr, (int)entry->ai_addrlen) == 0) {
				ready = true;
			}
			else {
				lastError = WSAGetLastError();
				if (lastError == WSAEWOULDBLOCK || lastError == WSAEINPROGRESS) {
					fd_set writeSet;
					FD_ZERO(&writeSet);
					FD_SET(candidate, &writeSet);
					fd_set errorSet = writeSet;
					timeval timeout;
					timeout.tv_sec = config.ConnectTimeoutMs / 1000;
					timeout.tv_usec = (config.ConnectTimeoutMs % 1000) * 1000;
					const int selected = select(0, nullptr, &writeSet, &errorSet, &timeout);
					if (selected == 0) {
						lastError = WSAETIMEDOUT;
					}
					else if (selected > 0) {
						int socketError = 0;
						int length = sizeof(socketError);
						getsockopt(candidate, SOL_SOCKET, SO_ERROR, reinterpret_cast<char*>(&socketError), &length);
						lastError = socketError;
						ready = (socketError == 0);
					}
					else {
						lastError = WSAGetLastError();
					}
				}
			}

			if (ready) {
				nonBlocking = 0;
				ioctlsocket(candidate, FIONBIO, &nonBlocking);
				BOOL noDelay = TRUE;
				setsockopt(candidate, IPPROTO_TCP, TCP_NODELAY,
					reinterpret_cast<const char*>(&noDelay), sizeof(noDelay));
				connected = static_cast<quintptr>(candidate);
			}
			else {
				closesocket(candidate);
			}
		}
		freeaddrinfo(result);

		if (connected == 0) {
			*error = socketError(lastError, QStringLiteral("Cannot connect to %1").arg(config.getAuthority()));
		}
		return connected;
	}

