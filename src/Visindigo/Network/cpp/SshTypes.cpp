	/*!
		\since Visindigo 0.18.0

		判断参数是否足以发起一次连接。

		它只检查"填没填全、取值合不合法"，不检查文件是否存在、主机是否可达——
		那些要等真正连接时才可能知道。

		\return 参数完整且自洽时返回 true。
	*/
	bool SshConnectConfig::isValid() const {
		if (Host.trimmed().isEmpty() || User.trimmed().isEmpty()) {
			return false;
		}
		if (Port < 1 || Port > 65535) {
			return false;
		}
		switch (AuthMethod) {
		case SshAuthMethod::Password:
			return !Password.isEmpty();
		case SshAuthMethod::PublicKey:
			return !PrivateKeyPath.isEmpty();
		case SshAuthMethod::PasswordOrPublicKey:
			return !Password.isEmpty() || !PrivateKeyPath.isEmpty();
		default:
			return false;
		}
	}

