	// 数值框与十六进制输入用填充式输入框样式：底色与面板背景拉开差距、描边常驻可见，
	// 这样用户一眼就能看出这里可以输入，而不是点上去才发现。所有颜色取自调色板，跟随主题切换。
	void ModernColorPickerPrivate::applyControlStyle() {
		const QPalette palette = q->palette();
		const QColor base = palette.color(QPalette::Base);
		const QColor text = palette.color(QPalette::WindowText);
		const QColor accent = palette.color(QPalette::Highlight);
		const QColor accentText = palette.color(QPalette::HighlightedText);
		const QColor fieldBackgroundBase = blendColor(base, text, 0.07);
		const QColor fieldBackgroundFocusedBase = blendColor(base, text, 0.03);
		// 输入框保持不透明：父级可能是半透明的毛玻璃面板，数值仍然要清晰。
		QColor fieldBackground = fieldBackgroundBase;
		fieldBackground.setAlphaF(1.0);
		QColor fieldBackgroundFocused = fieldBackgroundFocusedBase;
		fieldBackgroundFocused.setAlphaF(1.0);
		const QColor fieldBorder = withAlpha(text, 0.28);
		const QColor fieldBorderHover = withAlpha(text, 0.46);
		const QColor disabledText = withAlpha(text, 0.38);
		QColor disabledBackground = blendColor(base, text, 0.03);
		disabledBackground.setAlphaF(1.0);

		auto buildStyle = [&](const QString& selector) {
			return QStringLiteral(
				"%1 { background-color: %2; color: %3; border: 1px solid %4; border-radius: 5px;"
				" padding: 0px 5px; selection-background-color: %5; selection-color: %6; }"
				"%1:hover { border-color: %7; }"
				"%1:focus { border-color: %5; background-color: %8; }"
				"%1:disabled { color: %9; background-color: %10; border-color: %10; }")
				.arg(selector, fieldBackground.name(QColor::HexArgb), text.name(QColor::HexArgb),
					fieldBorder.name(QColor::HexArgb), accent.name(), accentText.name(),
					fieldBorderHover.name(QColor::HexArgb),
					fieldBackgroundFocused.name(QColor::HexArgb),
					disabledText.name(QColor::HexArgb), disabledBackground.name(QColor::HexArgb));
			};
		const QString spinStyle = buildStyle(QStringLiteral("QSpinBox"));
		const QString lineStyle = buildStyle(QStringLiteral("QLineEdit"));
		const QList<QSpinBox*> spinBoxes = q->findChildren<QSpinBox*>();
		for (QSpinBox* spinBox : spinBoxes) {
			spinBox->setStyleSheet(spinStyle);
			// 输入框光标是最直接的“可输入”提示。
			spinBox->setCursor(Qt::IBeamCursor);
			QLineEdit* editor = spinBox->findChild<QLineEdit*>();
			if (editor != nullptr) {
				editor->setCursor(Qt::IBeamCursor);
			}
		}
		HexEdit->setStyleSheet(lineStyle);
		HexEdit->setCursor(Qt::IBeamCursor);
	}

