	void ModernColorPicker_Wheel::ensureImages() {
		const qreal dpr = devicePixelRatioF();
		const QSize pixelSize(qMax(1, qRound(width() * dpr)), qMax(1, qRound(height() * dpr)));
		if (RingImage.isNull() or RingImagePixelSize != pixelSize) {
			rebuildRingImage();
		}
		if (TriangleImage.isNull() or TriangleImagePixelSize != pixelSize
			or qAbs(CachedHue - Hue) > HueCacheTolerance) {
			rebuildTriangleImage();
		}
	}

	void ModernColorPicker_Wheel::paintEvent(QPaintEvent* event) {
		Q_UNUSED(event);
		if (width() <= 0 or height() <= 0) {
			return;
		}
		ensureImages();
		QPainter painter(this);
		painter.setRenderHint(QPainter::Antialiasing, true);
		painter.setRenderHint(QPainter::SmoothPixmapTransform, true);
		painter.drawImage(0, 0, RingImage);
		painter.drawImage(0, 0, TriangleImage);
		// 内外圈各描一道极淡的边，避免色相环在浅色背景上糊掉。
		painter.setBrush(Qt::NoBrush);
		painter.setPen(QPen(QColor(0, 0, 0, 45), 1.0));
		const qreal outer = getOuterRadius();
		const qreal inner = getInnerRadius();
		painter.drawEllipse(getCenter(), outer, outer);
		painter.drawEllipse(getCenter(), inner, inner);
		// 色相环上的指示点：饱和度归零时三角上的标记贴在白黑边上，靠它才能看出当前色相。
		const qreal ringRadius = (getInnerRadius() + getOuterRadius()) / 2.0;
		const QPointF ringMarker = getPointAtAngle(Hue, ringRadius);
		painter.setBrush(Qt::NoBrush);
		painter.setPen(QPen(QColor(20, 20, 20, 190), 2.0));
		painter.drawEllipse(ringMarker, MarkerRadius - 1.0, MarkerRadius - 1.0);
		painter.setPen(QPen(QColor(255, 255, 255, 230), 1.2));
		painter.drawEllipse(ringMarker, MarkerRadius - 1.0, MarkerRadius - 1.0);
		const QPointF marker = getMarkerPosition();
		painter.setPen(QPen(QColor(20, 20, 20, 200), 2.4));
		painter.drawEllipse(marker, MarkerRadius, MarkerRadius);
		painter.setPen(QPen(QColor(255, 255, 255, 235), 1.4));
		painter.drawEllipse(marker, MarkerRadius, MarkerRadius);
	}

	void ModernColorPicker_Wheel::applyTrianglePoint(const QPointF& pos) {
		QPointF hueVertex, whiteVertex, blackVertex;
		getTriangleVertices(hueVertex, whiteVertex, blackVertex);
		qreal hueWeight = 0.0;
		qreal whiteWeight = 0.0;
		qreal blackWeight = 0.0;
		getTriangleWeights(hueVertex, whiteVertex, blackVertex, pos,
			hueWeight, whiteWeight, blackWeight);
		hueWeight = qMax(hueWeight, 0.0);
		whiteWeight = qMax(whiteWeight, 0.0);
		blackWeight = qMax(blackWeight, 0.0);
		const qreal sum = hueWeight + whiteWeight + blackWeight;
		if (sum <= 0.0) {
			return;
		}
		hueWeight /= sum;
		whiteWeight /= sum;
		Value = qBound(0.0, hueWeight + whiteWeight, 1.0);
		Saturation = Value > 0.0 ? qBound(0.0, hueWeight / Value, 1.0) : 0.0;
		notifyColorChanged();
	}

	void ModernColorPicker_Wheel::notifyColorChanged() {
		this->update();
		emit colorChanged(getColor());
	}

	void ModernColorPicker_Wheel::mousePressEvent(QMouseEvent* event) {
		if (event->button() != Qt::LeftButton) {
			QWidget::mousePressEvent(event);
			return;
		}
		const QPointF pos = event->position();
		const qreal radius = getRadiusOfPoint(pos);
		// 内圈全部算作三角区域：落在三角外的点会就近贴到三角边缘，避免中间留出死区。
		if (radius <= getInnerRadius()) {
			CurrentDrag = DragMode::Triangle;
			applyTrianglePoint(pos);
			event->accept();
			return;
		}
		if (radius <= getOuterRadius()) {
			CurrentDrag = DragMode::Hue;
			Hue = getAngleOfPoint(pos);
			notifyColorChanged();
			event->accept();
			return;
		}
		CurrentDrag = DragMode::None;
		QWidget::mousePressEvent(event);
	}

	void ModernColorPicker_Wheel::mouseMoveEvent(QMouseEvent* event) {
		if ((event->buttons() & Qt::LeftButton) == 0 or CurrentDrag == DragMode::None) {
			QWidget::mouseMoveEvent(event);
			return;
		}
		const QPointF pos = event->position();
		if (CurrentDrag == DragMode::Hue) {
			Hue = getAngleOfPoint(pos);
			notifyColorChanged();
		}
		else if (CurrentDrag == DragMode::Triangle) {
			applyTrianglePoint(pos);
		}
		event->accept();
	}

	void ModernColorPicker_Wheel::mouseReleaseEvent(QMouseEvent* event) {
		if (event->button() == Qt::LeftButton) {
			CurrentDrag = DragMode::None;
			event->accept();
			return;
		}
		QWidget::mouseReleaseEvent(event);
	}

