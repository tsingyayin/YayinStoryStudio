	void YSSConfigLangDocument::analyze() {
		if (d->HostEdit == nullptr) {
			return;
		}
		QStringList lines;
		QTextDocument* document = d->HostEdit->getDocument();
		for (QTextBlock block = document->begin(); block.isValid(); block = block.next()) {
			lines.append(block.text());
		}
		QList<YSSLangDiagnosticData> allDiags;
		if (d->AnalyzeFn) {
			d->AnalyzeFn(lines, &allDiags);
		}
		// 按行归拢，然后整篇替换一次（旧诊断随块上的数据一起被释放）。
		QMap<qint32, QList<YSSLangDiagnosticData>> byLine;
		for (const YSSLangDiagnosticData& diag : allDiags) {
			const qint32 line = diag.getLine();
			if (line >= 0 && line < lines.size()) {
				byLine[line].append(diag);
			}
		}
		// 诊断没变（行数也没变）说明这次分析是上一轮重新着色引出来的回声，到此为止：
		// 不替换行数据、不发出 contentChanged，否则会立刻再触发一次整篇重新着色，
		// 形成永不停歇的"着色-分析-重新着色"循环。
		// 但换过文档（重新打开、重载）后块上的数据会随着旧文本块一起消失，这种情况要重建。
		bool cacheAttached = true;
		for (auto it = byLine.begin(); it != byLine.end(); ++it) {
			if (d->HostEdit->getBlockData<YSSConfigLineData>(it.key()) == nullptr) {
				cacheAttached = false;
				break;
			}
		}
		if (cacheAttached && lines.size() == d->LastBlockCount && byLine == d->LastByLine) {
			return;
		}
		d->LastBlockCount = lines.size();
		d->LastByLine = byLine;
		d->HostEdit->removeAllBlockData<YSSConfigLineData>();
		for (auto it = byLine.begin(); it != byLine.end(); ++it) {
			YSSConfigLineData* data = new YSSConfigLineData();
			data->Diagnostics = it.value();
			d->HostEdit->setBlockData<YSSConfigLineData>(it.key(), data);
		}
		d->Analyzing = true;
		emit contentChanged();
		d->Analyzing = false;
	}

