	// ---------------------------------------------------------------------------
	static void colorIniLine(YSSConfigLangHighlighter* highlighter, const QString& text) {
		if (text.isEmpty()) return;
		highlighter->setFormatWithColorKey(0, text.length(), "PlainText");
		const QList<IniToken> tokens = lexIniLine(text, 0, nullptr);
		for (const IniToken& t : tokens) {
			switch (t.type) {
			case IniTokenType::Comment:
				highlighter->setFormatWithColorKey(t.column, t.length, "Comment");
				break;
			case IniTokenType::Section:
				highlighter->setFormatWithColorKey(t.column, t.length, "Section");
				break;
			case IniTokenType::Key:
				highlighter->setFormatWithColorKey(t.column, t.length, "Key");
				break;
			case IniTokenType::Value:
				highlighter->setFormatWithColorKey(t.column, t.length, "String");
				break;
			default:
				break; // Equals / Plain 保持 PlainText
			}
		}
	}

