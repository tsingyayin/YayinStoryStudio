	// INI 全文档分析
	// ---------------------------------------------------------------------------
	static void analyzeIniLines(const QStringList& lines, QList<YSSLangDiagnosticData>* diags) {
		if (!diags) return;
		QSet<QString> seenSections;
		QMap<QString, QSet<QString>> sectionKeys;
		QString currentSection;
		for (qint32 i = 0; i < lines.size(); ++i) {
			const QString& line = lines.at(i);
			const QList<IniToken> tokens = lexIniLine(line, i, diags);
			if (tokens.isEmpty()) continue;
			const IniToken& first = tokens.first();
			if (first.type == IniTokenType::Section) {
				QString name = first.text.mid(1);
				if (name.endsWith(QLatin1Char(']'))) name.chop(1);
				name = name.trimmed();
				if (name.length() >= 2 && name.startsWith(QLatin1Char('"')) && name.endsWith(QLatin1Char('"'))) {
					name = name.mid(1, name.length() - 2);
				}
				if (seenSections.contains(name)) {
					diags->append(YSSLangDiagnosticData(QStringLiteral("节 \"%1\" 重复定义").arg(name),
						i, first.column, qMax<qint32>(first.length, 1),
						YSSLangDiagnosticData::Severity::Warning, QStringLiteral("INI-DUP-SECTION")));
				}
				else {
					seenSections.insert(name);
				}
				currentSection = name;
			}
			else if (first.type == IniTokenType::Key) {
				QString key = first.text.trimmed();
				if (key.length() >= 2
					&& ((key.startsWith(QLatin1Char('"')) && key.endsWith(QLatin1Char('"')))
						|| (key.startsWith(QLatin1Char('\'')) && key.endsWith(QLatin1Char('\''))))) {
					key = key.mid(1, key.length() - 2);
				}
				if (key.isEmpty()) continue;
				if (sectionKeys[currentSection].contains(key)) {
					diags->append(YSSLangDiagnosticData(QStringLiteral("节 %1 中键 \"%2\" 重复").arg(
						currentSection.isEmpty() ? QStringLiteral("顶层") : currentSection, key),
						i, first.column, qMax<qint32>(key.length(), 1),
						YSSLangDiagnosticData::Severity::Warning, QStringLiteral("INI-DUP-KEY")));
				}
				else {
					sectionKeys[currentSection].insert(key);
				}
			}
		}
	}

