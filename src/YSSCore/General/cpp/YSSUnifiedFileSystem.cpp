	/*
		\since YSS 0.18.0

		等一条请求结束。

		\a reply 结果句柄，可为空。
		\a error 输出参数，失败原因，可为 nullptr。
		\a timeoutMs 超时毫秒数。

		return 请求完成且没有错误时返回 true。

		后端的完成通知是排队投递的，因此这里通常真的会进一次嵌套事件循环。超时的请求
		不会被取消——后端可能仍在执行，所以调用方不能直接销毁 reply。
	*/
	bool YSSUnifiedFileSystemPrivate::waitForReply(YSSFileSystemReply* reply, YSSFileError* error, int timeoutMs) {
		if (reply == nullptr) {
			if (error) {
				YSSFileError noBackend;
				noBackend.setType(YSSFileError::ErrorType::NotSupported);
				noBackend.setMessage(QStringLiteral("No filesystem backend handles this URI"));
				*error = noBackend;
			}
			return false;
		}
		if (!reply->isFinished()) {
			QEventLoop loop;
			QTimer timer;
			timer.setSingleShot(true);
			QObject::connect(reply, &YSSFileSystemReply::finished, &loop, &QEventLoop::quit);
			QObject::connect(&timer, &QTimer::timeout, &loop, &QEventLoop::quit);
			timer.start(timeoutMs);
			loop.exec();
			if (!reply->isFinished()) {
				YSSUFS->warning() << "sync wait timed out after" << timeoutMs << "ms for"
					<< describeRequest(reply->getId(), reply->getOperation(), reply->getUri());
			}
		}
		const bool finished = reply->isFinished();
		if (error) {
			if (finished) {
				*error = reply->getError();
			}
			else {
				YSSFileError timeout;
				timeout.setType(YSSFileError::ErrorType::IoError);
				timeout.setMessage(QStringLiteral("Timed out while waiting for the filesystem"));
				timeout.setDetail(reply->getUri().toString());
				*error = timeout;
			}
		}
		return finished && !reply->getError().isError();
	}

	/*!
		\since YSS 0.18.0

		同步读取整个文件。

		内部提交一条 YSSFileSystemRequest::Operation::Read 请求并等待它结束，
		因此会阻塞调用线程。界面线程上读远端文件应当改用 read() 异步版本。

		\a uri 文件身份。
		\a data 输出参数，读到的内容。
		\a error 输出参数，失败原因，可为 nullptr。

		return 读取成功返回 true。
	*/
	bool YSSUnifiedFileSystem::readSync(const YSSURI& uri, QByteArray* data, YSSFileError* error) {
		if (data == nullptr) {
			return false;
		}
		YSSFileSystemRequest request;
		request.setOperation(YSSUnifiedFileSystem::Operation::Read);
		request.setUri(uri);
		request.setAutoDelete(false);
		YSSFileSystemReply* reply = this->execute(request);
		const bool ok = this->d->waitForReply(reply, error);
		if (ok) {
			*data = reply->getData();
		}
		if (reply) {
			if (reply->isFinished()) {
				delete reply;
			}
			else {
				// 超时：请求可能还在后端执行，交给它完成后自行回收，避免悬空指针。
				reply->d->AutoDelete = true;
			}
		}
		return ok;
	}

