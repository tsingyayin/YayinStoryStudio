	YSSLocalOutcome computeLocal(const YSSCore::General::YSSFileSystemRequest& request,
		const ProgressCallback& report) {
		using namespace YSSCore::General;
		YSSLocalOutcome outcome;
		const QString detail = request.getUri().toString();
		const QString target = absolutePath(request.getUri());
		if (target.isEmpty()) {
			outcome.Error = makeLocalError(YSSFileError::ErrorType::InvalidConfiguration,
				QStringLiteral("Path is not usable on the local filesystem"), detail);
			return outcome;
		}

		switch (request.getOperation()) {
		case FileOperation::Stat: {
			const QFileInfo info(target);
			if (!info.exists()) {
				outcome.Error = makeLocalError(YSSFileError::ErrorType::NotFound,
					QStringLiteral("No such file or directory"), detail);
				return outcome;
			}
			outcome.Attributes = attributesOf(info);
			outcome.Ok = true;
			return outcome;
		}
		case FileOperation::Read: {
			QFile file(target);
			if (!file.exists()) {
				outcome.Error = makeLocalError(YSSFileError::ErrorType::NotFound,
					QStringLiteral("No such file"), detail);
				return outcome;
			}
			if (!file.open(QIODevice::ReadOnly)) {
				outcome.Error = makeLocalError(YSSFileError::ErrorType::PermissionDenied,
					QStringLiteral("Cannot open the file for reading"), file.errorString());
				return outcome;
			}
			outcome.Total = file.size();
			qint64 reported = 0;
			for (;;) {
				const QByteArray chunk = file.read(LocalChunkBytes);
				if (chunk.isEmpty()) {
					break;
				}
				outcome.Data.append(chunk);
				outcome.Bytes += chunk.size();
				if (report && outcome.Bytes - reported >= LocalProgressStepBytes) {
					reported = outcome.Bytes;
					report(outcome.Bytes, outcome.Total);
				}
			}
			if (file.error() != QFileDevice::NoError) {
				outcome.Error = makeLocalError(YSSFileError::ErrorType::IoError,
					QStringLiteral("Cannot read the file"), file.errorString());
				outcome.Data.clear();
				outcome.Bytes = 0;
				return outcome;
			}
			outcome.Ok = true;
			return outcome;
		}
		case FileOperation::Write: {
			QFile file(target);
			if (!file.open(QIODevice::WriteOnly | QIODevice::Truncate)) {
				outcome.Error = makeLocalError(YSSFileError::ErrorType::IoError,
					QStringLiteral("Cannot open the file for writing"), file.errorString());
				return outcome;
			}
			const QByteArray payload = request.getData();
			outcome.Total = payload.size();
			qint64 reported = 0;
			while (outcome.Bytes < payload.size()) {
				const qint64 written = file.write(payload.constData() + outcome.Bytes,
					qMin<qint64>(LocalChunkBytes, payload.size() - outcome.Bytes));
				if (written <= 0) {
					break;
				}
				outcome.Bytes += written;
				if (report && outcome.Bytes - reported >= LocalProgressStepBytes) {
					reported = outcome.Bytes;
					report(outcome.Bytes, outcome.Total);
				}
			}
			file.close();
			if (outcome.Bytes != payload.size()) {
				outcome.Error = makeLocalError(YSSFileError::ErrorType::IoError,
					QStringLiteral("Cannot write the file"), file.errorString());
				return outcome;
			}
			outcome.Ok = true;
			return outcome;
		}
		case FileOperation::List: {
			const QFileInfo info(target);
			if (!info.exists()) {
				outcome.Error = makeLocalError(YSSFileError::ErrorType::NotFound,
					QStringLiteral("No such directory"), detail);
				return outcome;
			}
			if (!info.isDir()) {
				outcome.Error = makeLocalError(YSSFileError::ErrorType::NotADirectory,
					QStringLiteral("Not a directory"), detail);
				return outcome;
			}
			const QDir dir(target);
			const QFileInfoList infos = dir.entryInfoList(QDir::NoDotAndDotDot | QDir::AllEntries);
			for (const QFileInfo& child : infos) {
				YSSFileEntry entry;
				entry.Name = child.fileName();
				entry.Attributes = attributesOf(child);
				outcome.Entries.append(entry);
			}
			outcome.Ok = true;
			return outcome;
		}
		case FileOperation::Remove: {
			YSSFileError removeError;
			if (!removeLocalRecursive(target, &removeError)) {
				outcome.Error = removeError;
				outcome.Error.Detail = detail;
				return outcome;
			}
			outcome.Ok = true;
			return outcome;
		}
		case FileOperation::Recycle: {
			if (!QFileInfo::exists(target) && !QFileInfo(target).isSymLink()) {
				outcome.Error = makeLocalError(YSSFileError::ErrorType::NotFound,
					QStringLiteral("No such file or directory"), detail);
				return outcome;
			}
			// moveToTrash 一次可以处理文件和整个目录树。失败时绝不退化成永久删除：
			// 告诉调用方这个位置不能回收，由它决定要不要改成 Remove。
			if (!QFile::moveToTrash(target)) {
				outcome.Error = makeLocalError(YSSFileError::ErrorType::NotSupported,
					QStringLiteral("This location cannot be recycled"), detail);
				return outcome;
			}
			outcome.Ok = true;
			return outcome;
		}
		case FileOperation::Rename: {
			const QString targetPath = absolutePath(request.getTargetUri());
			if (targetPath.isEmpty()) {
				outcome.Error = makeLocalError(YSSFileError::ErrorType::InvalidConfiguration,
					QStringLiteral("Target path is not usable on the local filesystem"), request.getTargetUri().toString());
				return outcome;
			}
			if (!QFileInfo::exists(target)) {
				outcome.Error = makeLocalError(YSSFileError::ErrorType::NotFound,
					QStringLiteral("No such file or directory"), detail);
				return outcome;
			}
			bool renamed = false;
			if (QFileInfo(target).isDir()) {
				renamed = QDir().rename(target, targetPath);
			}
			else {
				renamed = QFile::rename(target, targetPath);
			}
			if (!renamed) {
				outcome.Error = makeLocalError(YSSFileError::ErrorType::IoError,
					QStringLiteral("Cannot rename"), detail);
				return outcome;
			}
			outcome.Ok = true;
			return outcome;
		}
		case FileOperation::Mkdir: {
			if (QFileInfo::exists(target)) {
				outcome.Error = makeLocalError(YSSFileError::ErrorType::AlreadyExists,
					QStringLiteral("Already exists"), detail);
				return outcome;
			}
			if (!QDir().mkdir(target)) {
				outcome.Error = makeLocalError(YSSFileError::ErrorType::IoError,
					QStringLiteral("Cannot create the directory"), detail);
				return outcome;
			}
			outcome.Ok = true;
			return outcome;
		}
		case FileOperation::Rmdir: {
			const QFileInfo info(target);
			if (!info.exists()) {
				outcome.Error = makeLocalError(YSSFileError::ErrorType::NotFound,
					QStringLiteral("No such directory"), detail);
				return outcome;
			}
			if (!info.isDir()) {
				outcome.Error = makeLocalError(YSSFileError::ErrorType::NotADirectory,
					QStringLiteral("Not a directory"), detail);
				return outcome;
			}
			if (!QDir().rmdir(target)) {
				outcome.Error = makeLocalError(YSSFileError::ErrorType::IoError,
					QStringLiteral("Cannot remove the directory (is it empty?)"), detail);
				return outcome;
			}
			outcome.Ok = true;
			return outcome;
		}
		default:
			outcome.Error = makeLocalError(YSSFileError::ErrorType::NotSupported,
				QStringLiteral("Unsupported operation"));
			return outcome;
		}
	}
