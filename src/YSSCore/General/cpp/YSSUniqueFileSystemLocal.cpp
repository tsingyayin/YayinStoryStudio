			// 目录联接用 RemoveDirectoryW 才只删链接；符号链接两者皆可。
			if (::RemoveDirectoryW(reinterpret_cast<LPCWSTR>(native.utf16()))) {
				return true;
			}
			return ::DeleteFileW(reinterpret_cast<LPCWSTR>(native.utf16())) != 0;
