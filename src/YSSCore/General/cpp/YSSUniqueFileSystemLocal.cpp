	/*!
		\since YSS 0.18.0

		提交操作。实际的读写在工作线程池里执行，结果通过 \l{YSSFileSystemReply} 返回。

		\a request 操作参数。
		\a reply 结果对象。
	*/
	void YSSLocalFileSystemProvider::execute(const YSSFileSystemRequest& request, YSSFileSystemReply* reply) {
		if (reply == nullptr) {
			return;
		}
		if (!request.hasUri()) {
			this->fail(reply, makeLocalError(YSSFileError::ErrorType::InvalidConfiguration,
				QStringLiteral("The request carries no absolute URI")));
			return;
		}
		QObject::connect(reply, &QObject::destroyed, this, [this, reply]() {
			QMutexLocker locker(&this->d->Mutex);
			this->d->Outcomes.remove(reply);
		});
		YSSLocalFileSystemProvider* provider = this;
		QThreadPool::globalInstance()->start(new YSSLambdaRunnable([provider, request, reply]() {
			provider->runRequest(request, reply);
		}));
	}

	/*!
		\since YSS 0.18.0

		在工作线程里执行一条请求，然后把结果投递回结果对象所属线程。
		本函数由线程池调用，不要在调用方线程直接调用。

		\a request 操作参数。
		\a reply 结果对象。
	*/
	void YSSLocalFileSystemProvider::runRequest(const YSSFileSystemRequest& request, YSSFileSystemReply* reply) {
		this->markStarted(reply);
		const YSSLocalOutcome outcome = computeLocal(request,
			[this, reply](qint64 transferred, qint64 total) {
				this->reportProgress(reply, transferred, total);
			});
		{
			QMutexLocker locker(&this->d->Mutex);
			this->d->Outcomes.insert(reply, outcome);
		}
		QMetaObject::invokeMethod(this, [this, reply]() {
			this->deliverResult(reply);
		}, Qt::QueuedConnection);
	}

	/*!
		\since YSS 0.18.0

		在结果对象所属线程里把算好的结果交给它。结果对象已经销毁时丢弃。

		\a reply 结果对象。
	*/
	void YSSLocalFileSystemProvider::deliverResult(YSSFileSystemReply* reply) {
		YSSLocalOutcome outcome;
		{
			QMutexLocker locker(&this->d->Mutex);
			if (!this->d->Outcomes.contains(reply)) {
				return;
			}
			outcome = this->d->Outcomes.take(reply);
		}
		if (outcome.Ok) {
			this->complete(reply, outcome.Data, outcome.Entries, outcome.Attributes,
				outcome.Bytes, outcome.Total);
		}
		else {
			this->fail(reply, outcome.Error);
		}
	}
